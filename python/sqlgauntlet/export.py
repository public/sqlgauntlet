"""export: an app's database, as the SQLite reference built it, for another dialect, so every engine reads the same
data (the corpus's data generators are SQLite SQL; running a translation of them would test the translation):
  <p>.build.sql   CREATE TABLE for every ordinary table, its columns typed from their declared types and the values
                  they actually hold (SQLite lets a column hold any kind: one that does gets the dialect's text type),
                  its primary key kept (upserts need it)
  <p>.load.tsv    one CSV per table (csvn: \\N is NULL, blobs as the dialect's hex literal), for the driver's load
  <p>.post.sql    the indexes (unique ones too: ON CONFLICT needs them) and views, each translated by sqlglot, one
                  statement per block (blocks end with a line "-- end"): run.py runs each on its own, so one that fails
                  doesn't stop the rest; one that can't be translated is left out with a comment saying why
Virtual tables (FTS, R-tree) and their shadow tables are left out: they are SQLite features, and statements using
them are expected to fail on other engines. The reference database is read with Python's sqlite3 module."""

import re
import sqlite3
from pathlib import Path

from .dialect import transpile

TYPES = {
    'postgres': {'integer': 'bigint', 'real': 'double precision', 'text': 'text', 'blob': 'bytea'},
    'duckdb': {'integer': 'BIGINT', 'real': 'DOUBLE', 'text': 'VARCHAR', 'blob': 'BLOB'},
}


def affinity(decl):
    """SQLite's affinity rules (datatype3.html 3.1) for a declared type"""
    d = (decl or '').upper()
    if 'INT' in d:
        return 'integer'
    if any(x in d for x in ('CHAR', 'CLOB', 'TEXT')):
        return 'text'
    if 'BLOB' in d or not d:
        return 'blob'
    if any(x in d for x in ('REAL', 'FLOA', 'DOUB')):
        return 'real'
    return 'numeric'


def qi(name):
    """an identifier as the translated statements name it (dialect.transpile): lowercased and quoted"""
    return '"' + name.lower().replace('"', '""') + '"'


def field(v, dialect='postgres'):
    """a value as a csvn field: \\N for NULL, quoted when it must be (or when it is literally \\N); a blob in the text
    form the dialect casts to its blob type (postgres: \\x<hex>; duckdb: \\xHH per byte)"""
    if v is None:
        return '\\N'
    if isinstance(v, bytes):
        s = ''.join(f'\\x{b:02X}' for b in v) if dialect == 'duckdb' else '\\x' + v.hex()
    else:
        s = repr(v) if isinstance(v, float) else str(v)
    if s == '\\N' or any(c in s for c in ',"\n\r'):
        return '"' + s.replace('"', '""') + '"'
    return s


def export(db, out, p, dialect, log=None):
    """write <out>/<p>.build.sql, .load.tsv, .post.sql and <out>/<p>.data/<table>.csv; returns the notes"""
    import sqlglot

    tm = TYPES[dialect]
    con = sqlite3.connect(f'file:{db}?mode=ro', uri=True)
    rows = con.execute("SELECT type, name, tbl_name, sql FROM sqlite_master WHERE name NOT LIKE 'sqlite_%' ORDER BY rowid").fetchall()
    virtual = [n for t, n, _, sql in rows if t == 'table' and sql and re.match(r'\s*CREATE\s+VIRTUAL', sql, re.I)]
    shadow = lambda n: n in virtual or any(n.startswith(v + '_') for v in virtual)
    data = Path(out) / f'{p}.data'
    data.mkdir(parents=True, exist_ok=True)
    ddl, loads, post, notes = [], [], [], []
    for t, n, _, _sql in rows:
        if t != 'table' or shadow(n):
            continue
        # (table_xinfo: generated columns too, exported as plain columns holding their values; hidden 1 is a virtual
        #  table's hidden column)
        cols = [c[:6] for c in con.execute(f'PRAGMA table_xinfo({qi(n)})').fetchall() if c[6] != 1]  # cid, name, type, notnull, default, pk
        kinds = {c[1]: {k for (k,) in con.execute(f'SELECT DISTINCT typeof({qi(c[1])}) FROM {qi(n)}')} - {'null'} for c in cols}
        defs, rowid = [], None
        pkc = [c for c in cols if c[5]]
        if len(pkc) == 1 and (pkc[0][2] or '').upper() == 'INTEGER':
            rowid = pkc[0][1]  # (INTEGER PRIMARY KEY: SQLite's rowid, filled in when an insert leaves it out)
        for c in cols:
            a, have = affinity(c[2]), kinds[c[1]]
            if have <= {'integer'} and a in ('integer', 'numeric', 'real', 'blob') and have:
                ty = tm['integer'] if a != 'real' else tm['real']
            elif have <= {'integer', 'real'} and have:
                ty = tm['real']
            elif have == {'blob'}:
                ty = tm['blob']
            elif not have:
                ty = {'integer': tm['integer'], 'real': tm['real'], 'blob': tm['text'], 'numeric': tm['real']}.get(a, tm['text'])
            else:
                ty = tm['text']
            if c[1] == rowid and dialect == 'postgres':
                ty += ' GENERATED BY DEFAULT AS IDENTITY'
            elif c[1] == rowid and dialect == 'duckdb':  # (no identity columns, and no setval: a sequence that starts after the rows)
                start = (con.execute(f'SELECT max({qi(rowid)}) FROM {qi(n)}').fetchone()[0] or 0) + 1
                ddl.append(f'CREATE SEQUENCE {qi("sg_seq_" + n)} START {start};')
                ty += f" DEFAULT nextval('{qi('sg_seq_' + n)}')"
            defs.append(f'{qi(c[1])} {ty}')
        pk = [c[1] for c in sorted(cols, key=lambda c: c[5]) if c[5]]
        if pk and not con.execute(f'SELECT 1 FROM {qi(n)} WHERE ' + ' OR '.join(f'{qi(k)} IS NULL' for k in pk) + ' LIMIT 1').fetchone():
            defs.append(f'PRIMARY KEY ({", ".join(qi(k) for k in pk)})')  # (SQLite allows a NULL in a non-integer key)
        ddl.append(f'CREATE TABLE {qi(n)} ({", ".join(defs)});')
        f = data / f'{n}.csv'
        with open(f, 'w') as fh:
            for r in con.execute(f'SELECT {", ".join(qi(c[1]) for c in cols)} FROM {qi(n)}'):
                fh.write(','.join(field(v, dialect) for v in r) + '\n')
        if dialect == 'duckdb':  # (its own CSV reader: far faster than row-by-row inserts; a quoted \\N stays text, as in load;
            #  the dialect given, never sniffed, and an empty table not read at all: the sniffer refuses an empty file)
            if f.stat().st_size:
                ddl.append(f"COPY {qi(n)} FROM '{f.resolve()}' (FORMAT csv, HEADER false, DELIM ',', NULLSTR '\\N', ALLOW_QUOTED_NULLS false, QUOTE '\"', ESCAPE '\"');")
        else:
            loads.append(f'{qi(n)}\t{f.resolve()}\tcsvn')
        for _, ix, _, origin, _ in con.execute(f'PRAGMA index_list({qi(n)})').fetchall():
            if origin == 'u':  # (a UNIQUE constraint in the CREATE TABLE: an index with no SQL of its own; upserts need it)
                ic = [r[2] for r in con.execute(f'PRAGMA index_info({qi(ix)})').fetchall()]
                post.append(f'CREATE UNIQUE INDEX {qi("sg_" + ix)} ON {qi(n)} ({", ".join(qi(c) for c in ic)});')
        if rowid and dialect == 'postgres':  # (the identity continues after the loaded rows, as SQLite's rowid does)
            post.append(f"SELECT setval(pg_get_serial_sequence('{qi(n)}', '{rowid.lower()}'), coalesce(max({qi(rowid)}), 0) + 1, false) FROM {qi(n)};")
    for t, n, tbl, sql in rows:  # (indexes, then views, in the order SQLite has them)
        if t not in ('index', 'view') or not sql or shadow(tbl):
            continue
        try:
            post.append(';\n'.join(transpile(sqlglot, sql, dialect)) + ';')
        except Exception as e:
            why = str(e).splitlines()[0][:160]
            post.append(f'-- {t} {n} left out: {why}')
            notes.append(f'{p}: {t} {n}: {why}')
    post.append('ANALYZE;')
    post = [x + '\n-- end' for x in post]
    o = Path(out)
    (o / f'{p}.build.sql').write_text('\n'.join(ddl) + '\n')
    (o / f'{p}.load.tsv').write_text(''.join(line + '\n' for line in loads))
    (o / f'{p}.post.sql').write_text('\n'.join(post) + '\n')
    con.close()
    return notes
