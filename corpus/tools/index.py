#!/usr/bin/env python3
"""Rank projects and summarise the corpus from manifest.jsonl + projects/*/meta.json.

    tools/index.py            writes STATS.md and prints the ranking table that INDEX.md embeds

Scoring (also explained in INDEX.md):
  per-query complexity  cx = log2(VDBE ops) + sum of feature weights (WEIGHTS below)
  interest   I = mean cx of the project's 15 most complex queries, scaled so the corpus maximum is 10,
                 times (0.8 + 0.4 * share of queries tagged hotpath or hot-small), capped at 10
  visibility V = 2 * log10(stars / 1000) (umbrella repo's stars when the SQL lives in a sub-repo) clipped to [0, 5]  +  meta.reach (0-3, installs beyond GitHub)
                 - 1 if the last push is older than 180 days; scaled to 0-10 (max raw 8)
  score      S = I * V  (0-100)
"""
import json, math, re, sys
from collections import Counter
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEIGHTS = {"join3": 1, "correlated": 1, "cte": 1, "recursive-cte": 2, "window": 2, "subquery": 0.5,
           "groupby": 0.5, "having": 0.5, "fts": 1, "json": 1, "upsert": 0.5, "temp-btree": 0.5,
           "compound": 0.5, "exists": 0.5, "case": 0.25, "like": 0.25, "glob": 0.25, "date": 0.25,
           "string": 0.25, "multi-index-or": 0.5, "auto-index": 0.5}
TODAY = date(2026, 10, 28)


def cx(r):
    ops = r.get("vdbe_ops") or 1
    return round(math.log2(max(ops, 2)) + sum(WEIGHTS.get(t, 0) for t in r["tags"]), 2)


def main():
    rows = [json.loads(l) for l in open(ROOT / "manifest.jsonl")]
    for r in rows:
        r["cx"] = cx(r)
    projects = {}
    for p in sorted({r["project"] for r in rows}):
        meta = json.loads((ROOT / "projects" / p / "meta.json").read_text())
        qs = [r for r in rows if r["project"] == p]
        top = sorted((r["cx"] for r in qs), reverse=True)[:15]
        hot = sum(1 for r in qs if {"hotpath", "hot-small"} & set(r["tags"])) / len(qs)
        stars = meta.get("umbrella_stars") or meta.get("stars", 1000)
        stars_pts = min(5, max(0, 2 * math.log10(max(stars, 1) / 1000)))
        age = (TODAY - date.fromisoformat(meta.get("last_push", "2026-10-01"))).days
        vraw = stars_pts + meta.get("reach", 0) - (1 if age > 180 else 0)
        projects[p] = {"meta": meta, "n": len(qs), "hot": hot, "icx": sum(top) / len(top),
                       "V": round(max(0, vraw) / 8 * 10, 1), "stars_pts": round(stars_pts, 1),
                       "small": sum(1 for r in qs if "hot-small" in r["tags"]),
                       "ok": all(r["ok"] for r in qs)}
    mx = max(v["icx"] for v in projects.values())
    for v in projects.values():
        v["I"] = round(min(10, v["icx"] / mx * 10 * (0.8 + 0.4 * v["hot"])), 1)
        v["S"] = round(v["I"] * v["V"], 1)
    ranked = sorted(projects.items(), key=lambda kv: -kv[1]["S"])

    out = ["| # | Project | Stars | Reach | V | I | **Score** | Queries | hot-small | License | Category |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    for i, (p, v) in enumerate(ranked, 1):
        m = v["meta"]
        out.append(f"| {i} | [{m['name']}](projects/{p}/) | {m.get('stars', 0):,} | {m.get('reach', 0)} | {v['V']} | {v['I']} | "
                   f"**{v['S']}** | {v['n']} | {v['small']} | {m['license']} | {m.get('category', '')} |")
    print("\n".join(out))

    # STATS.md
    tags = Counter(t for r in rows for t in r["tags"])
    s = ["# Corpus statistics", "", "Generated by `tools/index.py` from `manifest.jsonl`. Don't edit by hand.", "",
         f"**{len(rows)} queries** from **{len(projects)} projects**, "
         f"{sum(1 for r in rows if r['ok'])} execute cleanly. "
         f"{sum(1 for r in rows if 'read' in r['tags'])} are reads and {sum(1 for r in rows if 'read' not in r['tags'])} are writes. "
         f"{tags['hot-small']} are tagged `hot-small`, {tags['hotpath']} `hotpath` and {tags['dynamic']} `dynamic` (built at runtime).", "",
         "## Tag distribution", "", "| Tag | Queries | Share |", "|---|---|---|"]
    for t, n in tags.most_common():
        s.append(f"| `{t}` | {n} | {n * 100 / len(rows):.0f}% |")
    s += ["", "## Complexity by project", "",
          "`cx` is `log2(VDBE ops)` plus feature weights; see `tools/index.py`.", "",
          "| Project | Queries | Median ops | Max ops | Mean cx (top 15) | Hot share | Joins (3+) | CTE | Window | FTS | JSON |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for p, v in ranked:
        qs = [r for r in rows if r["project"] == p]
        ops = sorted(r["vdbe_ops"] or 0 for r in qs)
        c = Counter(t for r in qs for t in r["tags"])
        s.append(f"| {p} | {len(qs)} | {ops[len(ops)//2]} | {ops[-1]} | {v['icx']:.1f} | {v['hot']:.0%} | {c['join3']} | "
                 f"{c['cte']} | {c['window']} | {c['fts']} | {c['json']} |")
    s += ["", "## Most complex queries", "", "| cx | ops | Query | Tags |", "|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: -r["cx"])[:40]:
        s.append(f"| {r['cx']} | {r['vdbe_ops']} | [`{r['id']}`]({r['src_url']}) | {', '.join(t for t in r['tags'] if t not in ('read',))} |")
    s += ["", "## Best specialiser targets: hot-path queries ranked by complexity", "",
          "These are the queries tagged `hotpath` that do the most engine work. They run often, and they're expensive.", "",
          "| cx | ops | Query | Tags |", "|---|---|---|---|"]
    for r in sorted((r for r in rows if "hotpath" in r["tags"]), key=lambda r: -r["cx"])[:40]:
        s.append(f"| {r['cx']} | {r['vdbe_ops']} | [`{r['id']}`]({r['src_url']}) | {', '.join(t for t in r['tags'] if t not in ('read', 'hotpath'))} |")
    # CPU-bound today: indicative stock timings (tools/time.py) plus public slowness reports
    timed = [r for r in rows if r.get("stock_ms_indicative") is not None]
    if timed:
        s += ["", "## CPU-bound today", "",
              "Indicative stock SQLite 3.54 wall time at scale 1, the minimum of 3 runs in one CLI process (`tools/time.py`; "
              "arm64 macOS, so it's triage only). The bench sessions own real measurements. A `cpu-evidence` "
              "tag means a public issue reports this query, or the page it serves, as slow; the links are in the "
              "project's `meta.json`.", "",
              "| Project | Queries | ≥ 10 ms | ≥ 100 ms | Slowest (ms) | Sum (ms) | Slowness reports |",
              "|---|---|---|---|---|---|---|"]
        byp = {}
        for r in timed:
            byp.setdefault(r["project"], []).append(r)
        for p, qs in sorted(byp.items(), key=lambda kv: -sum(r["stock_ms_indicative"] for r in kv[1])):
            ev = projects[p]["meta"].get("cpu_evidence", [])
            links = " ".join(f"[{i + 1}]({e['url']})" for i, e in enumerate(ev))
            mxq = max(qs, key=lambda r: r["stock_ms_indicative"])
            s.append(f"| {p} | {len(qs)} | {sum(1 for r in qs if r['stock_ms_indicative'] >= 10)} | "
                     f"{sum(1 for r in qs if r['stock_ms_indicative'] >= 100)} | {mxq['stock_ms_indicative']:.0f} | "
                     f"{sum(r['stock_ms_indicative'] for r in qs):.0f} | {links} |")
        s += ["", "### Slowest queries", "", "| ms | ops | Query | Tags |", "|---|---|---|---|"]
        for r in sorted(timed, key=lambda r: -r["stock_ms_indicative"])[:50]:
            s.append(f"| {r['stock_ms_indicative']:.1f} | {r['vdbe_ops']} | [`{r['id']}`]({r['src_url']}) | "
                     f"{', '.join(t for t in r['tags'] if t not in ('read',))} |")
    (ROOT / "STATS.md").write_text("\n".join(s) + "\n")
    json.dump({p: {k: v[k] for k in ("n", "I", "V", "S", "icx", "hot", "small")} for p, v in ranked},
              open(ROOT / "scores.json", "w"), indent=1)


if __name__ == "__main__":
    main()
